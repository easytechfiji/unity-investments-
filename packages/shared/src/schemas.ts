import { z } from 'zod';

// Lowercase words joined by single hyphens, for example "office-chairs".
// The same pattern is enforced by a check constraint in the database.
export const SLUG_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

export const slugSchema = z.string().min(1).max(200).regex(SLUG_PATTERN, 'Invalid slug');

// Database ids are bigint identity columns. They arrive as strings in URLs,
// so coerce and then insist on a positive whole number.
export const idSchema = z.coerce.number().int().positive().max(Number.MAX_SAFE_INTEGER);

export const MAX_LINE_QUANTITY = 999;

// One cart line as the browser stores it. There is deliberately no price here:
// the server always looks prices up in the database.
export const cartLineSchema = z.strictObject({
  productId: idSchema,
  variantId: idSchema.nullable(),
  quantity: z.number().int().min(1).max(MAX_LINE_QUANTITY),
});

export type CartLine = z.infer<typeof cartLineSchema>;

export const cartSchema = z.strictObject({
  lines: z.array(cartLineSchema).min(1).max(100),
});

export type Cart = z.infer<typeof cartSchema>;

// Fiji addresses -----------------------------------------------------------

export const FIJI_DIVISIONS = ['Central', 'Western', 'Northern', 'Eastern'] as const;
export type FijiDivision = (typeof FIJI_DIVISIONS)[number];

// Printable text with no control characters. Line breaks are not allowed in
// single line fields, which also blocks email header injection.
const singleLine = (max: number) =>
  z
    .string()
    .trim()
    .min(1, 'Required')
    .max(max, `Use ${max} characters or fewer`)
    .refine((value) => !/\p{Cc}/u.test(value), 'Must be a single line of text');

const optionalSingleLine = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Use ${max} characters or fewer`)
    .refine((value) => !/\p{Cc}/u.test(value), 'Must be a single line of text')
    .optional()
    .transform((value) => (value ? value : undefined));

export const emailSchema = z
  .string()
  .trim()
  .toLowerCase()
  .max(254)
  .pipe(z.email('Enter a valid email address'));

export const phoneSchema = z
  .string()
  .trim()
  .min(7, 'Enter a phone number')
  .max(20, 'Enter a phone number')
  .regex(/^\+?[0-9 ()-]{7,20}$/, 'Use digits, spaces and an optional + only');

export const addressSchema = z.strictObject({
  streetNumber: optionalSingleLine(20),
  streetName: singleLine(200),
  city: singleLine(100),
  division: z.enum(FIJI_DIVISIONS, 'Choose a division'),
});

export type Address = z.infer<typeof addressSchema>;

const recipientSchema = z.strictObject({
  firstName: singleLine(100),
  lastName: optionalSingleLine(100),
  phone: phoneSchema,
  address: addressSchema,
});

// Checkout -----------------------------------------------------------------

export const DELIVERY_METHODS = ['click_and_collect', 'shipping'] as const;
export const PAYMENT_METHODS = ['bank_transfer', 'paypal'] as const;

export const checkoutSchema = z
  .strictObject({
    // Generated by the checkout page once per attempt. Sending it twice returns the same order.
    checkoutToken: z.uuid(),
    email: emailSchema,
    firstName: singleLine(100),
    lastName: optionalSingleLine(100),
    phone: phoneSchema,
    address: addressSchema.optional(),
    shipToDifferentAddress: z.boolean().default(false),
    recipient: recipientSchema.optional(),
    deliveryMethod: z.enum(DELIVERY_METHODS),
    regionId: idSchema.optional(),
    paymentMethod: z.enum(PAYMENT_METHODS),
    note: z.string().trim().max(1000).optional(),
    lines: z.array(cartLineSchema).min(1, 'Your cart is empty').max(100),
    // The total the customer saw. Used only to warn them if prices changed, never to charge.
    expectedTotal: z
      .string()
      .regex(/^\d{1,10}\.\d{2}$/)
      .optional(),
  })
  .superRefine((value, ctx) => {
    if (value.deliveryMethod === 'shipping') {
      if (value.regionId === undefined) {
        ctx.addIssue({ code: 'custom', path: ['regionId'], message: 'Choose a delivery region' });
      }
      if (!value.address) {
        ctx.addIssue({ code: 'custom', path: ['address'], message: 'Enter a delivery address' });
      }
      if (value.shipToDifferentAddress && !value.recipient) {
        ctx.addIssue({
          code: 'custom',
          path: ['recipient'],
          message: 'Enter the delivery details',
        });
      }
    }
  });

export type CheckoutInput = z.input<typeof checkoutSchema>;
export type Checkout = z.output<typeof checkoutSchema>;

export const priceRequestSchema = z.strictObject({
  lines: z.array(cartLineSchema).max(100),
  deliveryMethod: z.enum(DELIVERY_METHODS).optional(),
  regionId: idSchema.optional(),
});

export const orderLookupSchema = z.strictObject({
  reference: z
    .string()
    .trim()
    .toLowerCase()
    .regex(/^[0-9a-f]{32}$/, 'Enter the 32 character reference from your email'),
  email: emailSchema,
});

export const paypalCaptureSchema = z.strictObject({
  reference: z.string().regex(/^[0-9a-f]{32}$/),
  paypalOrderId: z.string().regex(/^[A-Z0-9]{5,40}$/),
});

// Public forms -------------------------------------------------------------

const formBase = {
  name: singleLine(100),
  email: emailSchema,
  phone: phoneSchema.optional().or(z.literal('').transform(() => undefined)),
  message: z.string().trim().min(1, 'Required').max(3000, 'Use 3000 characters or fewer'),
  // Honeypot: hidden from people, so only bots fill it in.
  website: z.string().max(200).optional(),
  turnstileToken: z.string().max(4096).optional(),
};

export const contactFormSchema = z.strictObject({
  ...formBase,
  subject: optionalSingleLine(150),
});

export const quoteFormSchema = z.strictObject({
  ...formBase,
  productId: idSchema.optional(),
  quantity: z.coerce.number().int().min(1).max(100000).optional(),
  // Chosen from a product's quoteSizeOptions, when it has any.
  size: optionalSingleLine(100),
});

export type ContactForm = z.input<typeof contactFormSchema>;
export type QuoteForm = z.input<typeof quoteFormSchema>;
